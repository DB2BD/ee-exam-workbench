#!/usr/bin/env python3
from fractions import Fraction
import math

def audit_106_all():
    print("================ 106 年 電路學 全卷數值驗算 ================")
    
    # ----------------- 第 1 題：拉氏轉換求解 Vab(s) 與 vab(t) -----------------
    # Vin_ac = 6 cos(6t) u(t) => Vin_ac(s) = 6s / (s^2 + 36)
    # Vin_imp = 4 delta(t) => 4 (左- 右+ => 與 Vin_ac 串聯相加 => Vin(s) = 6s/(s^2+36) + 4)
    # 左側支路阻抗: Z_left = 2 + 2s = 2(s + 1)
    # 右側 a-b 端並聯: 2Ω, 8 delta(t) 電流源 (向上), 2F 電容 (1/(2s))
    # a-b 端總並聯阻抗: Zab(s) = 2 || (1/(2s)) = 2 / (4s + 1) = 1 / (2s + 0.5) = 0.5 / (s + 0.25)
    # 在節點 a 列寫 s 域 KCL (設 b 點為 0V):
    # (Va - Vin)/Z_left + Va/2 + Va/(1/(2s)) = 8
    # (Va - Vin)/(2s + 2) + 0.5 Va + 2s Va = 8
    # Va * [ 1/(2(s+1)) + (2s + 0.5) ] = 8 + Vin/(2(s+1))
    # 乘以 2(s+1):
    # Va * [ 1 + (4s + 1)(s + 1) ] = 16(s + 1) + Vin(s)
    # Va * [ 1 + 4s^2 + 5s + 1 ] = Va * (4s^2 + 5s + 2) = 16(s + 1) + 4 + 6s/(s^2 + 36) = 16s + 20 + 6s/(s^2 + 36)
    # Va(s) = (16s + 20) / (4s^2 + 5s + 2) + 6s / [ (4s^2 + 5s + 2)(s^2 + 36) ]
    print("[Q1] Vab(s) = (16s + 20) / (4s^2 + 5s + 2) + 6s / [(4s^2 + 5s + 2)(s^2 + 36)]")

    # ----------------- 第 4 題：對稱與反對稱分析法求 Io -----------------
    # 圖 4：
    # 左側電源 V_left = 30 V (+在上 -在下)
    # 右側電源 V_right = 60 V (+在上 -在下)
    # 輸出電流 Io 為流向左邊進入 1Ω (從 60V 正端流向左側)
    # 拓撲：
    # 頂部：1Ω -- (頂部中點 A) -- 2Ω -- (頂部中點 B) -- 1Ω
    # 底部：1Ω -- (底部中點 C) -- 2Ω -- (底部中點 D) -- 1Ω
    # 交叉斜線：A 連接 D (3Ω), B 連接 C (3Ω)
    
    # 偶模式 (Even Mode): V_e = (30 + 60)/2 = 45 V (左右皆為 +45V)
    # 奇模式 (Odd Mode): V_o = (60 - 30)/2 = 15 V (左為 -15V, 右為 +15V)
    
    # (1) 偶模式 (Even Mode: 左右皆為 +45V):
    # 垂直對稱軸（通過 2Ω 中點與 3Ω 交叉點）：
    # 左右對稱 => 對稱線上無水平電流流過 => 2Ω 電阻從中間斷開（開路 Open）
    # 交叉 3Ω 支路：左側由 A 往 D (電位與 B 往 C 對稱)，中點對稱開路
    # 從右半電路看：
    # 45V 電源串聯頂部 1Ω，到達節點 B
    # 節點 B 往左：2Ω 開路（0 電流）
    # 節點 B 往下接 3Ω 到中點（電位對稱相等，無電流 => 開路！）
    # 底部 1Ω 到達節點 D，往左 2Ω 開路
    # 故偶模式迴路電流 I_e:
    # 45V 經頂部 1Ω + 底部 1Ω (如果 3Ω 與 2Ω 全開路，迴路電流為 0? 不，3Ω 連接 B 與 C，在偶模式下 VC = VB ! 故 3Ω 跨壓為 0，電流為 0！)
    # 故偶模式下右側電源無迴路電流！ I_o,e = 0 A !
    
    # (2) 奇模式 (Odd Mode: 左 -15V, 右 +15V):
    # 奇對稱 => 對稱中心電位必為 0V（虛接地 Virtual Ground）
    # 頂部 2Ω 中點接地 (等效為 1Ω 接地)
    # 底部 2Ω 中點接地 (等效為 1Ω 接地)
    # 交叉 3Ω：節點 B(電位 V_B) 經 3Ω 到 節點 C(電位 -V_B)。中點電位為 0V！故等效為 1.5Ω 接地！
    # 右半電路：
    # 15V 電源 (+在頂部，-在底部)
    # 頂部：15V 正端 --(1Ω)--> 節點 B
    # 節點 B 連接：
    # 1. 頂部 2Ω 之半 (1Ω) 接地
    # 2. 交叉 3Ω 之半 (1.5Ω) 接地
    # 節點 B 對地等效電阻 R_B = 1Ω || 1.5Ω = (1 * 1.5) / (1 + 1.5) = 1.5 / 2.5 = 0.6 Ω
    # 底部：15V 負端 --(1Ω)--> 節點 D
    # 同理，節點 D 對地等效電阻 R_D = 1Ω || 1.5Ω = 0.6 Ω
    # 奇模式總等效電阻 R_odd = 1Ω (頂部) + R_B (0.6Ω) + R_D (0.6Ω) + 1Ω (底部) = 3.2 Ω
    # 奇模式輸出電流 I_o,o = 15V / R_odd = 15 / 3.2 = 150 / 32 = 75 / 16 = 4.6875 A
    
    # 總電流 Io = I_o,e + I_o,o = 0 + 4.6875 = 4.6875 A = 75/16 A
    I_o = Fraction(75, 16)
    print(f"[Q4] Even mode: I_oe = 0 A")
    print(f"[Q4] Odd mode: I_oo = {I_o} A = {float(I_o):.4f} A")
    print(f"[Q4] Total Io = {I_o} A ≈ {float(I_o):.4f} A")

if __name__ == '__main__':
    audit_106_all()
