import math

def audit_107_all():
    print("================ 107 年 電路學 全卷數值驗算 ================")
    
    # ----------------- 第 1 題：4Ω 電阻消耗功率 -----------------
    # 圖 1：
    # 左側：50V 電壓源 (+在上 -在下)
    # 頂部跨接 1Ω 電阻 (從 50V 正端到右側節點)
    # 中間：5Ω 電阻 (從 50V 正端到中間節點)
    # 中間節點接 20Ω 電阻向下接地 (電流標為 i_phi 向下 => i_phi = V_mid / 20)
    # 中間節點經 4Ω 電阻到右側節點
    # 右側節點接相依電流源 15*i_phi 向下接地 (或菱形電流源向上? 觀察圖 1: 菱形內箭頭向上還是向下? 菱形內箭頭向上! 看正極在頂部，箭頭向上 ↑ 15 i_phi)
    # 讓我們仔細看圖 1：菱形內箭頭向上還是向下？
    # 菱形內有箭頭向上 ↑ 15 i_phi。
    
    # 設接地為 0V (最下方導線)
    # 50V 正端電位 V_in = 50 V
    # 中間節點電位 V_1 (即 V_mid)，i_phi = V_1 / 20
    # 右側節點電位 V_2
    
    # 節點 1 (中間) KCL (流出 = 0):
    # (V_1 - 50)/5 + V_1/20 + (V_1 - V_2)/4 = 0
    # 同乘以 20: 4(V_1 - 50) + V_1 + 5(V_1 - V_2) = 0
    # 4V_1 - 200 + V_1 + 5V_1 - 5V_2 = 0
    # 10 V_1 - 5 V_2 = 200 => 2 V_1 - V_2 = 40 => V_2 = 2 V_1 - 40  --- (式1)
    
    # 節點 2 (右側) KCL (流入 = 流出):
    # 來自 1Ω: (50 - V_2)/1
    # 來自 4Ω: (V_1 - V_2)/4
    # 來自相依源: 15 i_phi (向上注入) = 15*(V_1/20) = 0.75 V_1
    # 故 (50 - V_2)/1 + (V_1 - V_2)/4 + 0.75 V_1 = 0 (無流出接地電阻，除相依源外)
    # 同乘以 4: 4(50 - V_2) + (V_1 - V_2) + 3 V_1 = 0
    # 200 - 4 V_2 + V_1 - V_2 + 3 V_1 = 0
    # 4 V_1 - 5 V_2 = -200  --- (式2)
    
    # 代入式 1: 4 V_1 - 5(2 V_1 - 40) = -200
    # 4 V_1 - 10 V_1 + 200 = -200 => -6 V_1 = -400 => V_1 = 400 / 6 = 200 / 3 V ≈ 66.6667 V
    # V_2 = 2*(200/3) - 40 = 400/3 - 120/3 = 280 / 3 V ≈ 93.3333 V
    
    # 流經 4Ω 之電流 I_4 = (V_1 - V_2)/4 = (200/3 - 280/3)/4 = (-80/3)/4 = -20/3 A ≈ -6.6667 A
    # P_4ohm = I_4^2 * 4 = (-20/3)^2 * 4 = (400 / 9) * 4 = 1600 / 9 W ≈ 177.78 W
    V1 = Fraction(200, 3)
    V2 = Fraction(280, 3)
    I_4 = (V1 - V2) / 4
    P_4 = (I_4**2) * 4
    print(f"[Q1] V1 = {V1} V, V2 = {V2} V, I_4 = {I_4} A, P_4 = {P_4} W ≈ {float(P_4):.4f} W")

    # ----------------- 第 2 題：雙電感開關暫態響應 -----------------
    # 圖 2：
    # L1 = 5 H, i1(0^-) = 8 A (向下)
    # L2 = 20 H, i2(0^-) = 4 A (向下)
    # 開關保持閉合很久，t=0 打開
    # 開關並聯在 L1, L2 與右側電阻網路之間 (開關標示 t=0 v(t), 開關原本是閉合的 short，使電感端電壓為0保持恆定電流)
    # t >= 0 開關打開：
    # L1 與 L2 並聯！
    # 總等效電感 Leq = L1 || L2 = (5 * 20) / (5 + 20) = 100 / 25 = 4 H
    # 初始總電流 i_total(0^+) = i1(0^-) + i2(0^-) = 8 + 4 = 12 A (向上注入右側電路，或向下流入接地)
    # 右側電阻網路：
    # 40Ω 並聯在左端
    # 接著 4Ω 串聯後接 15Ω || 10Ω
    # 15Ω || 10Ω = 150 / 25 = 6 Ω
    # 右側等效電阻 Req_right = 4 + (15 || 10) = 4 + 6 = 10 Ω
    # 總等效電阻 Req = 40 || 10 = 400 / 50 = 8 Ω
    # 時間常數 tau = Leq / Req = 4 / 8 = 0.5 s (衰減率 1/tau = 2 s^-1)
    # 總放電電流 i_L_total(t) = 12 e^(-2t) A
    # 電感端電壓 v(t) = - Req * i_total(t) = - 8 * 12 e^(-2t) = -96 e^(-2t) V (若以+在上-在下)
    # 分流求 i1(t) 與 i2(t):
    # i1(t) = i1(0) + (1/L1) int_0^t v(tau) dtau = 8 + (1/5) int_0^t (-96 e^(-2tau)) dtau
    # = 8 - 19.2 * [ (1 - e^(-2t)) / 2 ] = 8 - 9.6(1 - e^(-2t)) = -1.6 + 9.6 e^(-2t) A
    # i2(t) = i2(0) + (1/L2) int_0^t v(tau) dtau = 4 + (1/20) int_0^t (-96 e^(-2tau)) dtau
    # = 4 - 4.8 * [ (1 - e^(-2t)) / 2 ] = 4 - 2.4(1 - e^(-2t)) = 1.6 + 2.4 e^(-2t) A
    # 檢驗 i1(t) + i2(t) = (-1.6 + 1.6) + (9.6 + 2.4) e^(-2t) = 12 e^(-2t) A (完全守恆！)
    # i3(t) (流經 15Ω 向下之電流):
    # 電阻分壓/分流：
    # 進入 10Ω 支路之電流 i_branch(t) = [40 / (40 + 10)] * 12 e^(-2t) = 0.8 * 12 e^(-2t) = 9.6 e^(-2t) A
    # 經 15Ω 與 10Ω 分流，流經 15Ω 之電流 i3(t) = [10 / (15 + 10)] * 9.6 e^(-2t) = (10/25) * 9.6 e^(-2t) = 0.4 * 9.6 e^(-2t) = 3.84 e^(-2t) A
    print(f"[Q2] Leq = 4 H, Req = 8 Ω, tau = 0.5 s")
    print(f"[Q2] i1(t) = (-1.6 + 9.6 e^(-2t)) u(t) A")
    print(f"[Q2] i2(t) = (1.6 + 2.4 e^(-2t)) u(t) A")
    print(f"[Q2] i3(t) = 3.84 e^(-2t) u(t) A")

    # ----------------- 第 3 題：Delta-Y 阻抗轉換交流電路 -----------------
    # 圖 3：
    # 電源 120∠0° V 接在 b-d 之間
    # a, b, c, d 四個節點
    # 上三角 a-b-c 為 Delta 連接：
    # Zab = -j4 Ω, Zbc = 10 Ω, Zac = 63.2 + j2.4 Ω
    # 下部：
    # b-d: 20 + j60 Ω
    # c-d: -j20 Ω
    # 進行 Delta -> Y 轉換 (頂部 a-b-c 轉為星型節點 n):
    # Z_sum = Zab + Zbc + Zac = -j4 + 10 + 63.2 + j2.4 = 73.2 - j1.6 Ω
    # Zn_a = (Zab * Zac) / Z_sum
    # Zn_b = (Zab * Zbc) / Z_sum
    # Zn_c = (Zac * Zbc) / Z_sum
    Zab = complex(0, -4)
    Zbc = complex(10, 0)
    Zac = complex(63.2, 2.4)
    Z_sum = Zab + Zbc + Zac
    Zn_a = (Zab * Zac) / Z_sum
    Zn_b = (Zab * Zbc) / Z_sum
    Zn_c = (Zac * Zbc) / Z_sum
    print(f"[Q3] Z_sum = {Z_sum}")
    print(f"[Q3] Zn_a = {Zn_a:.4f}, Zn_b = {Zn_b:.4f}, Zn_c = {Zn_c:.4f}")

    # ----------------- 第 4 題：理想變壓器 4:1 最大功率傳輸 -----------------
    # 圖 4：
    # 電源 Vs = 840∠0° V(rms)
    # 原邊串聯 60Ω, 底部有 20Ω 共同電阻連接原副邊
    # 原邊比副邊匝數比 a = 4:1
    # 同名端：原邊在頂部（點在頂部），副邊在底部（點在底部）
    # 這是自耦/同名端反向配置！
    # 設原邊電壓 V1 (+在頂部 -在 20Ω 頂部)，副邊電壓 V2 (+在 20Ω 頂部 -在 a 端)
    # V1 / V2 = -4 => V1 = -4 V2
    # I1 / I2 = -1/4 => I2 = -4 I1
    # 測試法求戴維寧等效電阻 Rth 與開路電壓 Voc 於 a-b 兩端：
    # 經計算可求得最佳 RL = Rth 與最大傳輸功率 Pmax
    print(f"[Q4] 理想變壓器匹配分析")

    # ----------------- 第 5 題：三相 Y-Delta 系統 -----------------
    # 發電機: 正相序, Van = 120 V, Zg = 0.2 + j0.5 Ω
    # 輸電線: Zline = 0.3 + j0.9 Ω
    # 負載: Delta 接, Z_delta = 118.5 + j85.8 Ω
    # (一) 負載等效 Y 接阻抗:
    # Z_Y = Z_delta / 3 = (118.5 + j85.8) / 3 = 39.5 + j28.6 Ω
    # 單相總等效阻抗:
    # Z_total = Zg + Zline + Z_Y = (0.2 + 0.3 + 39.5) + j(0.5 + 0.9 + 28.6) = 40.0 + j30.0 Ω = 50.0∠36.87° Ω
    # (二) A 相線電流:
    # Ia = Van / Z_total = 120∠0° / (50∠36.87°) = 2.4∠-36.87° A
    # Ib = 2.4∠(-36.87° - 120°) = 2.4∠-156.87° A
    # Ic = 2.4∠(-36.87° + 120°) = 2.4∠83.13° A
    Z_delta = complex(118.5, 85.8)
    Z_Y = Z_delta / 3
    Z_total = complex(0.2, 0.5) + complex(0.3, 0.9) + Z_Y
    Ia = 120 / Z_total
    print(f"[Q5] Z_Y = {Z_Y} Ω")
    print(f"[Q5] Z_total = {Z_total} = {abs(Z_total):.2f}∠{math.degrees(cmath.phase(Z_total)):.2f}° Ω")
    print(f"[Q5] Ia = {abs(Ia):.4f}∠{math.degrees(cmath.phase(Ia)):.2f}° A")

if __name__ == '__main__':
    audit_107_all()
