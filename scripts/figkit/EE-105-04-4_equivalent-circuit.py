s += ac_source(XS, 135, r=22) + ac_source(XM, 135, r=22)
s += line(XS, 113, XS, YT) + line(XS, YT, 240, YT) + coil(240, YT, 340, YT, turns=5) + line(340, YT, XM, YT) + line(XM, YT, XM, 113)
s += line(XS, 157, XS, YB) + line(XS, YB, XM, YB) + line(XM, 157, XM, YB)
s += dot(190, YT) + dot(190, YB)
s += arrow(150, YT - 14, 200, YT - 14, color=RED)
s += end_group()
s += text(XS - 18, 108, [("n", "+")], anchor="middle")
s += text(XS - 18, 172, [("n", "−")], anchor="middle")
s += ctext(BLUE, XS - 32, 141, [("v", "V"), ("vsub", "ϕ")], anchor="end")
s += text(XM + 18, 108, [("n", "+")], anchor="middle")
s += text(XM + 18, 172, [("n", "−")], anchor="middle")
s += ctext(BLUE, XM + 32, 141, [("v", "E"), ("vsub", "f")])
s += text(290, 44, [("v", "jX"), ("vsub", "s")], anchor="middle")
s += ctext(RED, 175, 40, [("v", "I"), ("vsub", "a")], anchor="middle")
s += text(XS, 226, [("t", "電源（每相端電壓）")], anchor="middle")
s += text(XM, 226, [("t", "電動機內生電勢")], anchor="middle")
s += text(295, 256, [("v", "V"), ("vsub", "ϕ"), ("n", " = "), ("v", "E"), ("vsub", "f"), ("n", " + "), ("v", "jX"), ("vsub", "s"), ("v", "I"), ("vsub", "a"), ("t", "（"), ("v", "R"), ("vsub", "a"), ("t", " 忽略）")], anchor="middle")
s += footer()
open(pathlib.Path(__file__).resolve().parents[2].joinpath('02_題解/技師題解/04_電機機械/figures/EE-105-04-4-equivalent-circuit.svg'), 'w').write(s)
print(len(s))
