#!/usr/bin/env python3
from fractions import Fraction
import math

def audit_104_all():
    print("================ 104 年 電路學 全卷數值驗算 ================")
    
    # ----------------- 第 1 題：戴維寧等效電路 -----------------
    # 圖一：
    # 節點分析法求 a-b 開路電壓 Vth 與關閉獨立源求 Rth
    # 觀察電路結構：
    # 左側：9V 電壓源
    # 5Ω 電阻接在 9V 與中間節點 c 之間
    # 中間節點 c 接 25Ω 電阻至下方節點 d
    # 1.8A 電流源接在節點 c 與節點 a 之間（方向向右 -> a）
    # 20Ω 電阻接在 9V 正端與節點 a 之間 (跨接頂部)
    # 10Ω 電阻接在 9V 負端與下方節點 b 之間
    # 60Ω 電阻接在 a-b 兩端之間
    
    # 設 b 為參考地 0V
    # 節點 d 在 10Ω 左側，設電位為 Vd
    # 9V 負端即為節點 d，故 9V 正端電位為 Vd + 9
    # 連接關係：
    # 9V 正端 --(5Ω)--> 節點 c --(25Ω)--> 節點 d (9V 負端)
    # 9V 正端 --(20Ω)--> 節點 a
    # 節點 c --(1.8A)--> 節點 a
    # 節點 d --(10Ω)--> 節點 b (0V)
    # 節點 a --(60Ω)--> 節點 b (0V)
    
    # (1) 求 Rth（關閉獨立源：9V 短路，1.8A 開路）
    # 9V 短路 => 9V 正端與節點 d (9V 負端) 相連！
    # 此時：
    # 5Ω 與 25Ω 並聯接在 (9V節點) 與 (c節點) 之間，但 1.8A 開路，c 點懸空！故 5Ω 與 25Ω 不影響 a-b 看入阻抗！
    # 20Ω 接在 9V節點 與 a 之間
    # 10Ω 接在 9V節點 與 b 之間
    # 60Ω 接在 a 與 b 之間
    # 從 a-b 端看入：
    # 是 60Ω 並聯上 (20Ω + 10Ω)！
    # Rth = 60 || (20 + 10) = 60 || 30 = (60 * 30) / (60 + 30) = 1800 / 90 = 20 Ω！
    Rth = (60 * 30) / (60 + 30)
    print(f"[Q1] Rth = {Rth} Ω (精確整數 20 Ω)")
    
    # (2) 求 Voc = Vth (a-b 開路，無外部負載，60Ω 仍留在內部)
    # 設 b 為 0V
    # 節點 a 電位即為 Vth = Va
    # 設節點 d 電位為 Vd，則 9V 正端電位為 Vd + 9
    # 節點 c：流入 = 流出 => (Vd + 9 - Vc)/5 = (Vc - Vd)/25 + 1.8
    # 5*(Vd + 9 - Vc) = Vc - Vd + 45
    # 5*Vd + 45 - 5*Vc = Vc - Vd + 45
    # 6*Vc = 6*Vd => Vc = Vd !
    # 節點 a：流入 = 流出 => 1.8 + (Vd + 9 - Va)/20 = Va/60
    # 乘以 60: 108 + 3*(Vd + 9 - Va) = Va
    # 108 + 3*Vd + 27 - 3*Va = Va
    # 4*Va - 3*Vd = 135  --- (式1)
    
    # 整體電路 KCL (或以節點 b 列寫)：
    # 流入 d 節點之電流總和 = 0:
    # 來自 10Ω: (0 - Vd)/10
    # 來自 25Ω: (Vc - Vd)/25 = 0 (因 Vc = Vd)
    # 來自 9V 負端之電流 = 9V 正端流出電流 = (Vd + 9 - Vc)/5 + (Vd + 9 - Va)/20 = 9/5 + (Vd + 9 - Va)/20
    # 故 (0 - Vd)/10 + 9/5 + (Vd + 9 - Va)/20 = 0
    # 乘以 20: -2*Vd + 36 + Vd + 9 - Va = 0
    # -Vd - Va + 45 = 0 => Vd = 45 - Va --- (式2)
    
    # 代入式 1: 4*Va - 3*(45 - Va) = 135
    # 4*Va - 135 + 3*Va = 135
    # 7*Va = 270 => Va = 270 / 7 ≈ 38.5714 V
    Vth = Fraction(270, 7)
    print(f"[Q1] Vth = {Vth} V ≈ {float(Vth):.4f} V")

    # ----------------- 第 2 題：互感耦合與純實數阻抗 -----------------
    # a-b 埠看入阻抗 Zin = R1 + jwL1 + Zrefl
    # w = 4000 rad/s
    # L1 = 12.5 mH => wL1 = 4000 * 0.0125 = 50 Ω
    # R1 = 20 Ω
    # 二次側迴路：
    # L2 = 8 mH => wL2 = 4000 * 0.008 = 32 Ω
    # R2 = 5 Ω
    # C = 12.5 uF => Xc = 1/(4000 * 12.5e-6) = 20 Ω
    # Z22 = R2 + j(wL2 - 1/wC) = 5 + j(32 - 20) = 5 + j12 Ω
    # 互感 M = k * sqrt(L1 * L2) = k * sqrt(12.5e-3 * 8e-3) = k * sqrt(100e-6) = k * 10e-3 H = 0.01 * k H
    # wM = 4000 * 0.01 * k = 40 k Ω
    # 反映阻抗 Zrefl = (wM)^2 / Z22 = (40k)^2 / (5 + j12) = 1600 k^2 * (5 - j12) / (5^2 + 12^2) = 1600 k^2 * (5 - j12) / 169
    # 總輸入阻抗 Zin = 20 + j50 + Zrefl = [20 + (8000/169) k^2] + j[50 - (19200/169) k^2]
    # 純實數條件 => 虛部 = 0:
    # 50 = (19200 / 169) * k^2
    # k^2 = 50 * 169 / 19200 = 8450 / 19200 = 169 / 384 ≈ 0.4401
    # k = sqrt(169 / 384) = 13 / (8*sqrt(6)) = 13 / 19.596 ≈ 0.6634
    k2 = Fraction(169, 384)
    k_val = math.sqrt(169 / 384)
    print(f"[Q2] k^2 = {k2}, k = {k_val:.4f} (不是粗略的2.5，精確解為 13/(8√6) ≈ 0.6634)")

    # ----------------- 第 4 題：含相依源 RLC 一階/二階暫態 -----------------
    # 圖三：
    # ig(t) = 20 u(t) mA = 0.02 u(t) A
    # 並聯電阻 50Ω (跨壓 v_phi, +在下, -在上? 還是 +在上 -在下?)
    # 圖三標示：v_phi: +在下，-在上！
    # 電容 100 μF, 電感 1 H, 相依電流源 15*10^-3 v_phi (向下), 輸出電壓 vo(t) (+在上, -在下)
    # vo = -v_phi => v_phi = -vo
    # 故相依電流源向下的電流 = 15*10^-3 (-vo) = -0.015 vo (即向上注入 0.015 vo !)
    # 並聯 KCL at top node:
    # ig = i_R + i_C + i_dep + i_L
    # 0.02 = vo/50 + C * dvo/dt + (-0.015 vo) + (1/L) * int(vo dt)
    # (1/50 - 0.015) vo = (0.02 - 0.015) vo = 0.005 vo = vo / 200 !
    # 故等效電導 Geq = 0.005 S => 等效電阻 Req = 200 Ω !
    # 電路為二階並聯 RLC (Req = 200Ω, C = 100μF, L = 1H)
    # 特徵方程式: s^2 + (1/(Req*C)) s + 1/(LC) = 0
    # 1/(Req*C) = 1 / (200 * 100e-6) = 1 / 0.02 = 50 rad/s
    # 1/(LC) = 1 / (1 * 100e-6) = 10000 (rad/s)^2
    # s^2 + 50s + 10000 = 0
    # 判別式: 50^2 - 4*10000 = 2500 - 40000 = -37500 < 0 (欠阻尼 Underdamped!)
    # alpha = 25, omega_0 = 100, omega_d = sqrt(10000 - 625) = sqrt(9375) = 25*sqrt(15) ≈ 96.8246 rad/s
    # 穩態值 vo(∞) = 0 (電感穩態短路!)
    print(f"[Q4] alpha = 25, omega_d = {math.sqrt(9375):.4f} rad/s (二階欠阻尼暫態響應)")

    # ----------------- 第 5 題：雙埠網路 g 參數 -----------------
    # I1 = g11 V1 + g12 I2
    # V2 = g21 V1 + g22 I2
    # 圖四電路：
    # 埠 1: 20Ω + j10Ω 串聯進入中間節點
    # 中間有相依電壓源 100 I2 (菱形，+在上，-在下接地)
    # 500Ω 電阻連接中間節點與埠 2
    # 埠 2 並聯 -j50Ω 電容
    
    # 測試 1: 令 I2 = 0 (埠 2 開路)
    # I2 = 0 => 相依源 100 I2 = 0 (短路接地!)
    # 中間節點接地 (0V)!
    # 故從埠 1 看入：V1 = I1 * (20 + j10) => I1/V1 = 1 / (20 + j10) = (20 - j10)/500 = 0.04 - j0.02 S => g11 = 0.04 - j0.02 S
    # 埠 2 電壓 V2：中間節點為 0V，500Ω 與 -j50Ω 串聯但無電源 => V2 = 0 => g21 = V2/V1 = 0 !
    
    # 測試 2: 令 V1 = 0 (埠 1 短路接地)
    # 埠 2 注入電流 I2
    # 中間節點電位 V_mid = 100 I2
    # 埠 1 短路接地 => I1 = - V_mid / (20 + j10) = - 100 I2 / (20 + j10)
    # g12 = I1/I2 = -100 / (20 + j10) = -100*(20 - j10)/500 = -4 + j2
    # 埠 2 節點電壓 V2:
    # 注入 I2 於埠 2:
    # (V2 - V_mid)/500 + V2 / (-j50) = I2
    # V2/500 + j V2/50 = I2 + V_mid/500 = I2 + 100 I2 / 500 = I2 + 0.2 I2 = 1.2 I2
    # V2 * (1/500 + j 10/500) = 1.2 I2
    # V2 * (1 + j10)/500 = 1.2 I2 => V2 = 1.2 * 500 / (1 + j10) * I2 = 600 / (1 + j10) * I2
    # g22 = V2/I2 = 600 * (1 - j10) / (1 + 100) = 600 * (1 - j10) / 101 ≈ 5.9406 - j59.4059 Ω
    g11 = complex(20, -10) / 500
    g21 = 0
    g12 = -100 / complex(20, 10)
    g22 = 600 / complex(1, 10)
    print(f"[Q5] g11 = {g11} S")
    print(f"[Q5] g21 = {g21}")
    print(f"[Q5] g12 = {g12}")
    print(f"[Q5] g22 = {g22} Ω")

if __name__ == '__main__':
    audit_104_all()
