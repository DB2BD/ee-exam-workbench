"""EE-108-04-4 fig 1: synchronous motor per-phase circuit (motor convention, I_a flows into the machine)."""
import sys, pathlib; sys.path.insert(0, str(pathlib.Path(__file__).parent))
from svgkit import *
def ctext(c, *a, **k): return text(*a, **k).replace('fill="#000"', f'fill="{c}"')
W, H = 600, 285; YT, YB = 60, 200; XS, XM = 110, 470
s = header(W, H)
s += ac_source(XS, 130, r=22) + ac_source(XM, 130, r=22)
s += line(XS, 108, XS, YT) + line(XS, YT, 250, YT)
s += coil(250, YT, 350, YT, turns=5)
s += line(350, YT, XM, YT) + line(XM, YT, XM, 108)
s += line(XS, 152, XS, YB) + line(XS, YB, XM, YB) + line(XM, 152, XM, YB)
s += arrow(190, YT - 16, 235, YT - 16, color=RED)
s += end_group()
s += ctext(BLUE, XS - 34, 112, [("n", "+")], anchor="middle")
s += ctext(BLUE, XS - 34, 160, [("n", "−")], anchor="middle")
s += ctext(BLUE, XS - 40, 136, [("v", "V"), ("vsub", "ϕ")], anchor="end")
s += text(XM + 34, 112, [("n", "+")], anchor="middle")
s += text(XM + 34, 160, [("n", "−")], anchor="middle")
s += text(XM + 42, 136, [("v", "E"), ("vsub", "f")])
s += ctext(RED, 212, YT - 26, [("v", "I"), ("vsub", "a")], anchor="middle")
s += text(300, YT + 32, [("v", "jX"), ("vsub", "s"), ("n", " = "), ("v", "j"), ("n", "1.95 Ω")], anchor="middle")
s += text(XM, 270, [("t", "電動機內部")], anchor="middle")
s += ctext(BLUE, 270, 236, [("v", "V"), ("vsub", "ϕ"), ("n", " = 2300/√3 = 1327.91∠0° V（無窮匯流排）")], anchor="middle")
s += footer()
open(pathlib.Path(__file__).resolve().parents[2].joinpath('02_題解/技師題解/04_電機機械/figures/EE-108-04-4-equivalent-circuit.svg'), 'w').write(s)
print(len(s))
