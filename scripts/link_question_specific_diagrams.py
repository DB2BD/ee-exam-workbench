sol_dir = '📝 個人題解與錯題本/05_電力系統'
for fname in sorted(os.listdir(sol_dir)):
    if not fname.endswith('.md') or '全卷完整詳細題解' not in fname:
        continue
    
    m_yr = re.search(r'(\d{3})年', fname)
    if not m_yr:
        continue
    yr = m_yr.group(1)
    
    fpath = os.path.join(sol_dir, fname)
    with open(fpath, 'r', encoding='utf-8') as f:
        text = f.read()
        
    if yr in exact_diagrams:
        # First remove old full page png embeds
        text = re.sub(r'!\[\[\d{3}年_電機工程技師_電力系統_p\d+\.png\|\d+\]\]\n\*圖：[^\n]*\*\n*', '', text)
        
        for q_prefix, img_embed in exact_diagrams[yr].items():
            pattern = r'(##\s*' + re.escape(q_prefix) + r'[^\n]*\n+###\s*📌\s*題目與已知條件[^\n]*\n+)'
            
            def repl(m):
                header_part = m.group(1)
                return header_part + img_embed + '\n\n'
                
            text = re.sub(pattern, repl, text)
            
    with open(fpath, 'w', encoding='utf-8') as f:
        f.write(text)
        
    print(f'✅ Updated {fname} with exact question-specific diagrams!')
