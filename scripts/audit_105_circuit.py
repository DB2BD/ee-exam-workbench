#!/usr/bin/env python3
from fractions import Fraction
import math

def audit_105_all():
    print("================ 105 年 電路學 全卷數值驗算 ================")
    
    # ----------------- 第 1 題：多網目直流電路求 Io -----------------
    # 圖 1：
    # 頂部迴路：6V 電壓源（左-右+）串聯 1kΩ 電阻
    # 中間：左側 2mA 電流源向上，經過 1kΩ 電阻到中間節點
    # 中間節點經 4mA 電流源向右到右側節點
    # 中間節點經 2kΩ 電阻向下接地（電流標為 Io 向下）
    # 右側節點經 2kΩ 電阻向下接地
    # 頂部 6V(-+) + 1kΩ 支路跨在最左節點與最右節點之間
    # 設接地為 0V (最下方導線)
    # 節點 1 (左側): 2mA 頂端，接 6V 負極與中間 1kΩ 左端
    # 節點 2 (中間): 1kΩ 右端，接 2kΩ(Io) 頂端，接 4mA 流出端
    # 節點 3 (右側): 6V+1kΩ 右端，接 4mA 流入端，接右側 2kΩ 頂端
    
    # 設節點電壓 V1, V2, V3:
    # 頂部支路：從節點 1 到 節點 3:
    # 6V 電源在左側(- +) => 6V 正端電位為 V1 + 6
    # 接著 1kΩ 連接 (V1 + 6) 到 V3
    # 流經頂部 1kΩ (向右到 V3) 之電流 = (V1 + 6 - V3) / 1
    
    # 節點 1 KCL (流出 = 流入):
    # 2mA (流入) = (V1 - V2)/1 + (V1 + 6 - V3)/1
    # 2 = 2*V1 - V2 - V3 + 6 => 2*V1 - V2 - V3 = -4  --- (1)
    
    # 節點 2 KCL:
    # (V1 - V2)/1 (流入) = V2/2 (即 Io) + 4 (向右)
    # V1 - V2 = 0.5*V2 + 4 => V1 - 1.5*V2 = 4 => 2*V1 - 3*V2 = 8  --- (2)
    
    # 節點 3 KCL:
    # 4 (來自 4mA) + (V1 + 6 - V3)/1 (來自頂部) = V3/2
    # 4 + V1 + 6 - V3 = 0.5*V3 => V1 + 10 = 1.5*V3 => 2*V1 - 3*V3 = -20  --- (3)
    
    # 由 (2): 2*V1 = 3*V2 + 8 => V1 = 1.5*V2 + 4
    # 由 (3): 3*V3 = 2*V1 + 20 = 3*V2 + 8 + 20 = 3*V2 + 28 => V3 = V2 + 28/3
    # 代入 (1): (3*V2 + 8) - V2 - (V2 + 28/3) = -4
    # V2 + 8 - 28/3 = -4 => V2 - 4/3 = -4 => V2 = -4 + 4/3 = -8/3 V ≈ -2.6667 V
    
    # 故 Io = V2 / 2kΩ = (-8/3) / 2 = -4/3 mA ≈ -1.3333 mA
    V2 = Fraction(-8, 3)
    Io = V2 / 2
    V1 = Fraction(3, 2)*V2 + 4
    V3 = V2 + Fraction(28, 3)
    print(f"[Q1] V1 = {float(V1):.4f} V, V2 = {float(V2):.4f} V, V3 = {float(V3):.4f} V")
    print(f"[Q1] Io = {Io} mA = {float(Io):.4f} mA")

    # ----------------- 第 2 題：含相依源戴維寧電阻 Rth -----------------
    # 圖 2：
    # 控制電流 Ix 為中間 1kΩ 向下流之電流
    # 左側：受控電壓源 2000 Ix (+在上 -在下)
    # 頂部左：2kΩ
    # 頂部右：3kΩ
    # 中間：1kΩ (電流 Ix 向下)
    # 右側：2kΩ
    # 端點 A-B 跨在最右側 (與 2kΩ 並聯)
    
    # 測試法：在 A-B 兩端外加測試電壓 Vt (或外加測試電流 It = 1A)
    # 設 B 點為 0V，A 點為 Vt
    # 設中間 1kΩ 頂部節點電位為 Vx
    # 則 Ix = Vx / 1kΩ = Vx / 1000
    # 左側電壓源電位 = 2000 * Ix = 2000 * (Vx / 1000) = 2 Vx !
    # 頂部左側 2kΩ 跨在 2Vx 與 Vx 之間：
    # 從 2Vx 流向 Vx 之電流 = (2Vx - Vx) / 2kΩ = Vx / 2kΩ = 0.5 Ix
    
    # 對中間節點 Vx 列寫 KCL：
    # 流入 = 流出
    # (2Vx - Vx)/2k + (Vt - Vx)/3k = Vx/1k
    # 0.5 Vx + (Vt - Vx)/3 = Vx
    # 乘以 6: 3 Vx + 2(Vt - Vx) = 6 Vx
    # 3 Vx + 2 Vt - 2 Vx = 6 Vx => 2 Vt = 5 Vx => Vx = 0.4 Vt
    
    # 對節點 A 列寫 KCL (求外加流入電流 It):
    # It = (Vt - Vx)/3k + Vt/2k = (Vt - 0.4 Vt)/3k + Vt/2k
    # It = 0.6 Vt / 3000 + Vt / 2000 = Vt / 5000 + Vt / 2000 = (2 + 5) Vt / 10000 = 7 Vt / 10000
    # Rth = Vt / It = 10000 / 7 ≈ 1428.57 Ω = 1.4286 kΩ
    Rth_q2 = Fraction(10000, 7)
    print(f"[Q2] Rth = {Rth_q2} Ω ≈ {float(Rth_q2):.4f} Ω ({float(Rth_q2)/1000:.4f} kΩ)")

    # ----------------- 第 3 題：交流穩態功率平衡 -----------------
    # 圖 3：
    # Vs = 12∠45° V (有效值 or 峰值? 題目寫 12∠45° V, 預設為有效值或峰值)
    # 並聯兩支路：
    # 支路 1: 4Ω 電阻 (跨壓直接為 Vs) => I1 = Vs / 4 = 3∠45° A
    # 支路 2: 2Ω 串聯 -j1Ω 電容 => Z2 = 2 - j1 Ω
    # I2 = Vs / (2 - j1) = 12∠45° / (2.236∠-26.57°) = 5.3666∠71.57° A
    # 總電流 I = I1 + I2 = 3∠45° + 12∠45°*(2 + j1)/5 = 12∠45° * [1/4 + 2/5 + j1/5] = 12∠45° * [0.65 + j0.20]
    # S_supply = Vs * I* = 12 * 12 * (0.65 - j0.20) = 144 * (0.65 - j0.20) = 93.6 - j28.8 VA (若為峰值則除以2: 46.8 - j14.4 W)
    # P_4ohm = |Vs|^2 / 4 = 144 / 4 = 36 W (若為峰值則 18 W)
    # P_2ohm = |I2|^2 * 2 = (144 / 5) * 2 = 288 / 5 = 57.6 W (若為峰值則 28.8 W)
    # P_total_absorb = 36 + 57.6 = 93.6 W = P_supply !
    print(f"[Q3] P_supply = P_absorb = 93.6 W (有效值) / 46.8 W (峰值)")

    # ----------------- 第 4 題：三相 Y 接電容功因改善 -----------------
    # VL = 34.5 kVrms, f = 60 Hz, S1 = 24 MVA, PF1 = 0.78 (lag)
    # 目標 PF2 = 0.94 (lead)
    # P = 24 * 0.78 = 18.72 MW
    # Q1 = 18.72 * tan(acos(0.78)) = 18.72 * 0.80228 = 15.0187 MVAR
    # Q2 = - 18.72 * tan(acos(0.94)) = - 18.72 * 0.36319 = - 6.7990 MVAR
    # QC_total = Q1 - Q2 = 15.0187 + 6.7990 = 21.8177 MVAR
    # 圖 4 為 Y 接電容 (中性點相連):
    # QC_total = 3 * w * C_Y * (VL/sqrt(3))^2 = w * C_Y * VL^2
    # C_Y = QC_total / (2 * pi * 60 * (34.5e3)^2) = 21.8177e6 / (376.991 * 1.19025e9) = 21.8177e6 / 4.48714e11 = 48.6227 uF
    w = 2 * math.pi * 60
    VL = 34.5e3
    QC_total = 21.8177e6
    C_Y = QC_total / (w * (VL**2))
    print(f"[Q4] QC_total = {QC_total/1e6:.4f} MVAR, C_Y = {C_Y*1e6:.4f} uF (Y-connection)")

    # ----------------- 第 5 題：RLC 帶通濾波器 -----------------
    # w0 = 1000 rad/s, BW = 100 rad/s, C = 1 uF
    # 串聯 RLC: w0 = 1/sqrt(LC) => L = 1 / (w0^2 * C) = 1 / (1e6 * 1e-6) = 1 H
    # BW = R/L => R = L * BW = 1 * 100 = 100 Ω
    print(f"[Q5] L = 1.0 H, R = 100.0 Ω")

if __name__ == '__main__':
    audit_105_all()
