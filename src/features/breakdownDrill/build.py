# -*- coding: utf-8 -*-
"""Build the per-question data of the v1.7.0 破題訓練 (breakdown drill).

For every PE canonical note: the primary chapter id (QUESTION_TAXONOMY_MAP in
dashboard-data.js, the same chapter the anchor statistics use), its primary 題型
(data/taxonomy/question-types.json) and the 「**解題邏輯**：」 paragraph of
「## 考場標準作答」, shown after the reveal.  The 題型 table (name, cues, first
move, prerequisites, confusers) is emitted too.

Writes data.generated.js next to this script (const BREAKDOWN_DRILL, BREAKDOWN_DRILL_TYPES).
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CANONICAL_GLOB = "02_題解/技師題解/0*/canonical/EE-*.md"
DASHBOARD_DATA = ROOT / "dashboard-data.js"
QUESTION_TYPES = ROOT / "data" / "taxonomy" / "question-types.json"
CORRECTIONS = ROOT / "data" / "taxonomy" / "chapter-corrections.json"
OUTPUT = HERE / "data.generated.js"

LOGIC_RE = re.compile(r"^\*\*解題邏輯\*\*：(.*?)(?=\n\s*\n|\Z)", re.M | re.S)
TAXONOMY_RE = re.compile(r"QUESTION_TAXONOMY_MAP = (\{.*?\n\});", re.S)


def taxonomy():
    match = TAXONOMY_RE.search(DASHBOARD_DATA.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit("dashboard-data.js: QUESTION_TAXONOMY_MAP not found")
    return json.loads(match.group(1))


def logic_of(text):
    match = LOGIC_RE.search(text)
    return match.group(1).strip() if match else ""


def question_types():
    data = json.loads(QUESTION_TYPES.read_text(encoding="utf-8"))
    keep = ("subject", "chapter", "name", "cues", "firstMove", "prereqs", "confusers")
    types = {tid: {k: t[k] for k in keep if k in t} for tid, t in data["types"].items()}
    return types, data["questions"]


def build():
    tax = taxonomy()
    types, typed = question_types()
    corrected = {c["qid"]: c["to"] for c in json.loads(CORRECTIONS.read_text(encoding="utf-8"))["corrections"]}
    out = {}
    problems = []
    for path in sorted(ROOT.glob(CANONICAL_GLOB)):
        qid = path.stem
        chapter = (tax.get(qid) or {}).get("primaryChapter", "")
        logic = logic_of(path.read_text(encoding="utf-8"))
        if not chapter:
            problems.append(f"{qid}: no primaryChapter")
        if not logic:
            problems.append(f"{qid}: no 解題邏輯 paragraph")
        qtype = (typed.get(qid) or {}).get("type", "")
        if qtype not in types:
            problems.append(f"{qid}: no 題型 in question-types.json")
        elif types[qtype]["chapter"] != chapter and (tax.get(qid) or {}).get("source") != "manual-topic-confirmed" \
                and corrected.get(qid) != types[qtype]["chapter"]:
            # The 題型 chapter may differ from the statistics chapter only for a learner-confirmed label or a reviewed
            # correction (data/taxonomy/chapter-corrections.json) that is not yet applied to the statistics.
            problems.append(f"{qid}: 題型 {qtype} is in {types[qtype]['chapter']}, question chapter is {chapter}")
        out[qid] = {"chapter": chapter, "type": qtype, "logicMd": logic}
    return out, types, problems


def main():
    data, types, problems = build()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    body = json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True)
    text = ("// AUTO-GENERATED by src/features/breakdownDrill/build.py — do not edit.\n"
            "// 破題訓練: primary chapter id and the 「解題邏輯」 paragraph of each PE canonical note.\n"
            f"const BREAKDOWN_DRILL = {body};\n"
            f"const BREAKDOWN_DRILL_TYPES = {json.dumps(types, ensure_ascii=False, indent=1, sort_keys=True)};\n")
    old = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if old != text:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(data)} questions, {len(types)} types)")
    else:
        print(f"{OUTPUT.relative_to(ROOT)} up to date ({len(data)} questions, {len(types)} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
