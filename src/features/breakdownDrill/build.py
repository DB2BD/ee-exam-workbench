# -*- coding: utf-8 -*-
"""Build the per-question data of the v1.7.0 破題訓練 (breakdown drill).

For every PE canonical note: the primary chapter id (QUESTION_TAXONOMY_MAP in
dashboard-data.js, the same chapter the anchor statistics use) and the
「**解題邏輯**：」 paragraph of 「## 考場標準作答」, shown after the reveal.

Writes data.generated.js next to this script (const BREAKDOWN_DRILL).
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CANONICAL_GLOB = "02_題解/技師題解/0*/canonical/EE-*.md"
DASHBOARD_DATA = ROOT / "dashboard-data.js"
OUTPUT = HERE / "data.generated.js"

LOGIC_RE = re.compile(r"^\*\*解題邏輯\*\*：(.*?)(?=\n\s*\n|\Z)", re.M | re.S)
TAXONOMY_RE = re.compile(r"QUESTION_TAXONOMY_MAP = (\{.*?\n\});", re.S)


def taxonomy():
    match = TAXONOMY_RE.search(DASHBOARD_DATA.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit("dashboard-data.js: QUESTION_TAXONOMY_MAP not found")
    return json.loads(match.group(1))


def logic_of(text):
    match = LOGIC_RE.search(text)
    return match.group(1).strip() if match else ""


def build():
    tax = taxonomy()
    out = {}
    problems = []
    for path in sorted(ROOT.glob(CANONICAL_GLOB)):
        qid = path.stem
        chapter = (tax.get(qid) or {}).get("primaryChapter", "")
        logic = logic_of(path.read_text(encoding="utf-8"))
        if not chapter:
            problems.append(f"{qid}: no primaryChapter")
        if not logic:
            problems.append(f"{qid}: no 解題邏輯 paragraph")
        out[qid] = {"chapter": chapter, "logicMd": logic}
    return out, problems


def main():
    data, problems = build()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    body = json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True)
    text = ("// AUTO-GENERATED by src/features/breakdownDrill/build.py — do not edit.\n"
            "// 破題訓練: primary chapter id and the 「解題邏輯」 paragraph of each PE canonical note.\n"
            f"const BREAKDOWN_DRILL = {body};\n")
    old = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if old != text:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(data)} questions)")
    else:
        print(f"{OUTPUT.relative_to(ROOT)} up to date ({len(data)} questions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
