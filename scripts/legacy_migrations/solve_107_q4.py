#!/usr/bin/env python3
from fractions import Fraction

def solve_107_q4():
    # 變數定義
    # a-b 埠開路時：
    # RL 斷開
    # 原邊電流 I1 從頂部流進點端
    # 副邊開路 => I2 = 0 => I1 = 0
    # 當 I1 = 0 時，原邊 60Ω 無壓降，20Ω 也無電流 => 20Ω 頂部電位 = 0V
    # 原邊電壓 V1 = Vs = 840 V
    # 理想變壓器關係：
    # 點在原邊頂部(+)，點在副邊底部(+)
    # V1 / V2 = -4 (因副邊標示 + 在頂部 a 端，- 在底部 20Ω 處) => V2 = -V1 / 4 = -840 / 4 = -210 V
    # 故 Voc = Va - Vb = V2 + V_20ohm = -210 + 0 = -210 V (幅值 210 V)
    
    # 戴維寧等效電阻 Rth:
    # 關閉獨立源 Vs = 0 (短路)
    # 在 a-b 端外加測試電壓 Vt，流入測試電流 It
    # 副邊電流 I2 = It (從 a 端流入頂部)
    # 依理想變壓器電流關係：
    # 原邊同名端流入電流 I1 與副邊同名端流入電流之和滿足 N1 I1 + N2 I2_dot = 0
    # 副邊電流 It 是從非同名端流入 => 從同名端流出 It
    # 故 I2_dot = -It
    # 4 * I1 + 1 * (-It) = 0 => I1 = It / 4
    
    # 電路各處電流：
    # 流經 60Ω 之電流 = I1 = It / 4
    # 流經 20Ω 之電流 = (原邊回到 20Ω 頂部之電流) + (副邊回到 20Ω 頂部之電流)
    # 原邊電流 I1 流經原邊繞組後向下到達 20Ω 頂部
    # 副邊電流 It 流經副邊繞組後向下到達 20Ω 頂部
    # 故流經 20Ω 向下接地之總電流 I_20 = I1 + It = It/4 + It = 1.25 It
    # 20Ω 頂部對地電位 V_mid = 20 * (1.25 It) = 25 It
    
    # 原邊迴路 KVL:
    # 原邊繞組跨壓 V1 = 0 - (60 * I1 + V_mid) = - (60 * (It/4) + 25 It) = - (15 It + 25 It) = -40 It
    # 副邊繞組跨壓 V2 = - V1 / 4 = - (-40 It) / 4 = 10 It
    
    # 測試端電壓 Vt = V2 + V_mid = 10 It + 25 It = 35 It
    # 故 Rth = Vt / It = 35 Ω !
    
    # (一) 最大功率傳輸條件：
    # RL = Rth = 35 Ω
    
    # (二) 最大平均功率值：
    # Pmax = |Voc|^2 / (4 * Rth) = (210)^2 / (4 * 35) = 44100 / 140 = 315 W
    
    print(f"Voc = -210 V (|Voc| = 210 V)")
    print(f"Rth = 35 Ω")
    print(f"RL = 35 Ω")
    print(f"Pmax = 315 W")

if __name__ == '__main__':
    solve_107_q4()
